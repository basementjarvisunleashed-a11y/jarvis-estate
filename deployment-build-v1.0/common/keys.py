"""Key ceremony — Phase 0 (paper §6.1: "Key ceremony; intent log; seal verification").

TEST KEYS ONLY. These keys are generated locally, marked TEST at every
layer, and are NEVER real credentials. The deployment's first act is the
key ceremony (paper §7.1: keys live in the governance plane — never on the
surfaces, never in the pull responses).

The ceremony writes:
    phase0/keys/CEREMONY-TEST        -- marker: these are test keys
    phase0/keys/master.seal.key      -- seals envelopes (governance plane)
    phase0/keys/<surface>.key        -- per-surface enrollment keys

load_keys() refuses to load unless the TEST marker is present, so test keys
can never be mistaken for production keys.
"""
import os
import secrets

KEY_DIR = os.path.join(os.path.dirname(os.path.dirname(
    os.path.abspath(__file__))), "phase0", "keys")
MARKER = "CEREMONY-TEST"
MARKER_TEXT = (
    "TEST KEYS ONLY — generated by the Phase 0 key ceremony.\n"
    "Never real credentials. Never leave this directory.\n"
    "Governance plane holds keys; surfaces never see them (paper §7.1).\n"
)


class KeyError(Exception):
    pass


def ceremony_generate(key_dir: str = KEY_DIR, surfaces=()) -> dict:
    """Run the key ceremony. Returns {name: key_bytes}."""
    # SAF-08: key material is owner-only (dir 0700, files 0600) whatever
    # the umask; test keys today, the same code path for real ones later.
    os.makedirs(key_dir, mode=0o700, exist_ok=True)
    os.chmod(key_dir, 0o700)
    with open(os.path.join(key_dir, MARKER), "w", encoding="utf-8") as fh:
        fh.write(MARKER_TEXT)
    keys = {"master": secrets.token_bytes(32)}
    for s in surfaces:
        keys["surface:%s" % s] = secrets.token_bytes(32)
    for name, kb in keys.items():
        path = os.path.join(key_dir, name.replace(":", "_") + ".key")
        # 0600 is applied by open() and again by fchmod, so a umask cannot
        # widen it. O_NOFOLLOW refuses to write the key through a symlink.
        flags = os.O_WRONLY | os.O_CREAT | os.O_TRUNC
        if hasattr(os, "O_NOFOLLOW"):
            flags |= os.O_NOFOLLOW
        fd = os.open(path, flags, 0o600)
        os.fchmod(fd, 0o600)
        with os.fdopen(fd, "wb") as fh:
            fh.write(kb)
    return keys


def load_keys(key_dir: str = KEY_DIR) -> dict:
    """Load ceremony keys. Refuses unless the TEST marker is present."""
    marker = os.path.join(key_dir, MARKER)
    if not os.path.isfile(marker):
        raise KeyError("no %s marker — refusing to load keys" % MARKER)
    keys = {}
    for fn in sorted(os.listdir(key_dir)):
        if fn.endswith(".key"):
            name = fn[:-4].replace("_", ":", 1) if fn.startswith("surface_") \
                else fn[:-4]
            # surface keys are stored as surface_<id>.key
            if fn.startswith("surface_"):
                name = "surface:" + fn[len("surface_"):-4]
            with open(os.path.join(key_dir, fn), "rb") as fh:
                keys[name] = fh.read()
    if "master" not in keys:
        raise KeyError("master seal key missing")
    return keys


def is_test_keyset(key_dir: str = KEY_DIR) -> bool:
    return os.path.isfile(os.path.join(key_dir, MARKER))
